-- Dashboard login accounts. Passwords are BCrypt hashes; the four demo users
-- (one per role) are created at startup by security/SeedUsers, since their
-- password comes from the environment and must not be committed here.

CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL
        CONSTRAINT app_users_role_check CHECK (role IN ('ANALYST', 'LEAD', 'AUDITOR', 'ADMIN')),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE
);
