-- Phase 4 audit log, exactly as Hibernate's ddl-auto: update originally created it.
-- Existing databases already have this table and are baselined at V1 (see
-- spring.flyway.baseline-on-migrate in application.yml); fresh ones run it.

CREATE TABLE cluster_decisions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT                   NOT NULL,
    decided_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    decision     VARCHAR(255)             NOT NULL
        CONSTRAINT cluster_decisions_decision_check CHECK (decision IN ('CONFIRM', 'DISMISS')),
    reason       VARCHAR(255)             NOT NULL
);
